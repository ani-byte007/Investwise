function buildDeterministicOhlcv(
  seed: number,
  endPrice: number,
  days = 240
): OhlcvBar[] {
  let state = seed >>> 0;
  const nextRand = () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 4294967296;
  };

  // Generate backwards from latest business date 2026-11-17
  const bars: OhlcvBar[] = [];
  let price = endPrice;
  const endDate = new Date('2026-11-17T00:00:00Z');
  let cursor = new Date(endDate);

  while (bars.length < days) {
    const day = cursor.getUTCDay();
    if (day !== 0 && day !== 6) {
      const pctMove = (nextRand() - 0.485) * 0.026;
      const close = Math.max(20, Math.round(price * 100) / 100);
      const open = Math.max(20, Math.round(close / (1 + pctMove) * 100) / 100);
      const spread = Math.abs(close - open) + close * (0.004 + nextRand() * 0.011);
      const high = Math.round((Math.max(open, close) + spread * 0.55) * 100) / 100;
      const low = Math.round((Math.min(open, close) - spread * 0.45) * 100) / 100;
      const volume = Math.round((1200000 + nextRand() * 4800000));

      bars.push({
        time: cursor.toISOString().slice(0, 10),
        open,
        high,
        low,
        close,
        volume,
      });

      price = open;
    }
    cursor.setUTCDate(cursor.getUTCDate() - 1);
  }

  return bars.reverse();
}

